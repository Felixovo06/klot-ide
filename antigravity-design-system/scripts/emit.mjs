// emit.mjs — derive consumable CSS variables + tailwind config from tokens.json
import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd(); // run from package root
const OUT = path.join(ROOT, 'out');
const t = JSON.parse(fs.readFileSync(path.join(OUT, 'tokens.json'), 'utf8'));

// ---------- tokens.css ----------
const decls = (mode, hc) => {
  const out = [];
  for (const [group, entries] of Object.entries(t.color[mode])) {
    if (!entries || typeof entries !== 'object') continue;
    for (const [name, v] of Object.entries(entries)) {
      if (!v || typeof v !== 'object') continue;
      const value = hc ? v.highContrast : v.$value;
      if (value) out.push(`--ag-${group}-${name}: ${value};`);
    }
  }
  return out;
};

const rule = (selector, lines, indent = '') =>
  `${indent}${selector} {\n${lines.map((l) => `${indent}  ${l}`).join('\n')}\n${indent}}`;

const typeVars = Object.entries(t.typography.scale).flatMap(([n, v]) => [
  `--ag-text-${n}: ${v.$value};`,
  `--ag-text-${n}--line-height: ${v.lineHeight};`,
]);
const spaceVars = Object.entries(t.space.scale).map(([n, v]) => `--ag-space-${n}: ${v};`);
const radiusVars = Object.entries(t.radius.app).map(([n, v]) => `--ag-radius-${n}: ${v};`);

const coreVars = [
  ...typeVars,
  ...spaceVars,
  ...radiusVars,
  `--ag-font-sans: ${t.typography.family.sans};`,
  `--ag-font-mono: ${t.typography.family.mono};`,
  `--ag-weight-light: ${t.typography.weight.light};`,
  `--ag-weight-normal: ${t.typography.weight.normal};`,
  `--ag-weight-medium: ${t.typography.weight.medium};`,
  `--ag-weight-semibold: ${t.typography.weight.semibold};`,
  `--ag-weight-bold: ${t.typography.weight.bold};`,
  `--ag-ease-expo-out: ${t.motion.ease.expoOut};`,
  `--ag-ease-cubic-out: ${t.motion.ease.cubicOut};`,
  `--ag-ease-standard: ${t.motion.ease.standard};`,
  `--ag-duration-fast: ${t.motion.duration.fast}ms;`,
  `--ag-duration-normal: ${t.motion.duration.normal}ms;`,
  `--ag-duration-slow: ${t.motion.duration.slow}ms;`,
];

const css = `/* Antigravity 2.32.2 design tokens — generated by emit.mjs, do not edit */
/* source: language_server UI bundle (theme map "onyx") + jetbox component layer */

${rule(':root, [data-theme="light"]', [...decls('light', false), ...coreVars])}

@media (prefers-color-scheme: dark) {
${rule(':root:not([data-theme="light"])', decls('dark', false), '  ')}
}

${rule('[data-theme="dark"]', decls('dark', false))}

/* high contrast (token carries a second value for this) */
${rule('[data-contrast="high"]', decls('light', true))}

${rule('[data-theme="dark"][data-contrast="high"]', decls('dark', true))}

body {
  font-family: var(--ag-font-sans);
  font-size: var(--ag-text-base);
  line-height: var(--ag-text-base--line-height);
  font-weight: var(--ag-weight-normal);
  background: var(--ag-surface-canvas);
  color: var(--ag-content-primary);
}

h1, h2 { letter-spacing: -0.015em; }
h3 { letter-spacing: -0.008em; }
`;

fs.writeFileSync(path.join(OUT, 'tokens.css'), css);

// ---------- tailwind.config.js ----------
const colors = {};
for (const [group, entries] of Object.entries(t.color.dark)) {
  if (!entries || typeof entries !== 'object') continue;
  const inner = Object.entries(entries)
    .filter(([, v]) => v && typeof v === 'object' && v.$value)
    .map(([n]) => `        '${n}': 'var(--ag-${group}-${n})',`);
  if (inner.length) colors[group] = `{\n${inner.join('\n')}\n      }`;
}

const colorsJs = `{\n${Object.entries(colors)
  .map(([g, body]) => `      ${g}: ${body},`)
  .join('\n')}\n    }`;

const fontSizeJs = `{\n${Object.entries(t.typography.scale)
  .map(([n, v]) => `      '${n}': ['${v.$value}', '${v.lineHeight}'],`)
  .join('\n')}\n    }`;

const spacingJs = `{\n${Object.entries(t.space.scale)
  .map(([n, v]) => `      '${n}': '${v}',`)
  .join('\n')}\n    }`;

const radiusJs = `{\n${Object.entries(t.radius.app)
  .map(([n, v]) => `      '${n}': '${v}',`)
  .join('\n')}\n    }`;

const zJs = `{\n${Object.entries(t.zIndex)
  .map(([n, v]) => `      '${n}': ${v},`)
  .join('\n')}\n    }`;

const tw = `// Antigravity 2.32.2 — generated by emit.mjs
// colors resolve through tokens.css custom properties, so switching
// light/dark is a class flip, not a rebuild.

/** @type {import('tailwindcss').Config} */
module.exports = {
  theme: {
    extend: {
      colors: ${colorsJs},
      fontSize: ${fontSizeJs},
      spacing: ${spacingJs},
      borderRadius: ${radiusJs},
      boxShadow: {
        glass: '0 12px 32px -12px rgb(16 32 80 / 0.18), 0 2px 6px -2px rgb(16 32 80 / 0.06)',
        peek: '8px 0 24px -8px rgb(0 0 0 / 0.16)',
      },
      transitionTimingFunction: {
        'expo-out': '${t.motion.ease.expoOut}',
        'cubic-out': '${t.motion.ease.cubicOut}',
        standard: '${t.motion.ease.standard}',
      },
      zIndex: ${zJs},
    },
  },
};
`;

fs.writeFileSync(path.join(OUT, 'tailwind.config.js'), tw);
console.log('emitted tokens.css, tailwind.config.js');
